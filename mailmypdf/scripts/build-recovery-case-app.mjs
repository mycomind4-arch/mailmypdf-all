import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(root, "src/lib/mcp/recovery-case-client.ts"), "utf8");
const { outputText, diagnostics } = ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    removeComments: true,
  },
  reportDiagnostics: true,
});
if (diagnostics?.some((d) => d.category === ts.DiagnosticCategory.Error))
  throw new Error("Recovery case app did not compile");
const output =
  "// Generated by scripts/build-recovery-case-app.mjs; edit recovery-case-client.ts.\nexport const RECOVERY_CASE_CLIENT_SOURCE = " +
  JSON.stringify(outputText + "\nmountRecoveryCaseApp(window, document);\n") +
  ";\n";
const destination = path.join(root, "src/lib/mcp/generated/recovery-case-client.ts");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== output) {
    console.error(
      "Recovery case app bundle is stale. Run node scripts/build-recovery-case-app.mjs.",
    );
    process.exitCode = 1;
  }
} else {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, output);
}
