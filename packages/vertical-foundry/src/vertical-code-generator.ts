/**
 * Vertical Code Generator — produces the file set for a generated vertical.
 *
 * Given a VerticalCandidate and build configuration, generates a complete
 * static site (or framework project) that can be deployed to Cloudflare Pages.
 *
 * Generated code never contains credentials, API keys, or secrets.
 * All configuration is injected at deployment time via environment variables.
 */

import type { VerticalCandidate } from './foundry-contract.js'
import type { BuildFile, BuildConfig, BuildFramework } from './vertical-manifest.js'

export interface CodeGenRequest {
  candidate: VerticalCandidate
  framework: BuildFramework
  domain: string
}

export interface CodeGenResult {
  files: BuildFile[]
  buildConfig: BuildConfig
}

export function generateVerticalCode(request: CodeGenRequest): CodeGenResult {
  const { candidate, framework, domain } = request

  switch (framework) {
    case 'static':
      return generateStaticSite(candidate, domain)
    case 'astro':
      return generateAstroSite(candidate, domain)
    case 'next':
      return generateNextSite(candidate, domain)
    case 'vite':
      return generateViteSite(candidate, domain)
    default:
      return generateStaticSite(candidate, domain)
  }
}

function slugify(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
}

