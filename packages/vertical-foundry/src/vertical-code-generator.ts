function generateAstroSite(candidate: VerticalCandidate, domain: string): CodeGenResult {
  // For now, generate a static site with an astro.config.mjs stub
  const staticResult = generateStaticSite(candidate, domain)
  return {
    files: [
      ...staticResult.files,
      {
        path: 'astro.config.mjs',
        description: 'Astro configuration',
        content: `import { defineConfig } from 'astro/config'\n\nexport default defineConfig({\n  site: 'https://${domain}',\n  output: 'static',\n})\n`,
      },
    ],
    buildConfig: {
      framework: 'astro',
      entryPoint: 'src/pages/index.astro',
      files: staticResult.files,
      dependencies: { astro: '^4.0.0' },
      buildCommand: 'astro build',
      outputDir: 'dist',
    },
  }
}

function generateNextSite(candidate: VerticalCandidate, domain: string): CodeGenResult {
  const staticResult = generateStaticSite(candidate, domain)
  return {
    files: [
      ...staticResult.files,
      {
        path: 'next.config.js',
        description: 'Next.js configuration',
        content: `/** @type {import('next').NextConfig} */\nmodule.exports = {\n  output: 'export',\n  reactStrictMode: true,\n}\n`,
      },
    ],
    buildConfig: {
      framework: 'next',
      entryPoint: 'pages/index.js',
      files: staticResult.files,
      dependencies: { next: '^14.0.0', react: '^18.0.0', 'react-dom': '^18.0.0' },
      buildCommand: 'next build',
      outputDir: 'out',
    },
  }
}

function generateViteSite(candidate: VerticalCandidate, domain: string): CodeGenResult {
  const staticResult = generateStaticSite(candidate, domain)
  return {
    files: [
      ...staticResult.files,
      {
        path: 'vite.config.js',
        description: 'Vite configuration',
        content: `import { defineConfig } from 'vite'\n\nexport default defineConfig({\n  build: { outDir: 'dist' },\n})\n`,
      },
    ],
    buildConfig: {
      framework: 'vite',
      entryPoint: 'index.html',
      files: staticResult.files,
      dependencies: { vite: '^5.0.0' },
      buildCommand: 'vite build',
      outputDir: 'dist',
    },
  }
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;')
}
